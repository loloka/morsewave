// Префикс для ключей кириллицы в Progress.learnedLetters — латинская A и
// кириллическая А обязаны быть разными записями (см. CLAUDE.md, бэклог п.1).
const CYRILLIC_PREFIX = 'RU_';

// Символ (без префикса) физически совпадает по коду с Е — принимаем оба
// варианта ответа как верный (см. комментарий у CYRILLIC_CODE выше).
function isCyrillicMatch(decoded, target) {
    return decoded === target || (target === 'Ё' && decoded === 'Е') || (target === 'Е' && decoded === 'Ё');
}

// Ключ прогресса по самому символу — в отличие от progressKeyFor() в
// learn.js (который смотрит на выбранный порядок/режим UI), эта версия не
// завязана на состояние интерфейса: нужна там, где известна только буква и
// неважно, как она попала на экран (например, приём на слух со "Своими
// символами" может вперемешку выдавать и латинские, и кириллические цели).
function progressKeyForChar(ch) {
    return CYRILLIC_LEARNABLE.includes(ch) ? CYRILLIC_PREFIX + ch : ch;
}

