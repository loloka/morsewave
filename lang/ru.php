<h2>2. Вариант с Arduino — если хочется компактную плату, а не целую клавиатуру</h2>
<p>Если куда-то пристраивать полноразмерную клавиатуру-донор неудобно,
    тот же результат даёт маленькая плата на <b>ATmega32u4</b> с «настоящим»
    USB (не через отдельный USB-serial чип) — например, <b>Arduino Pro
    Micro</b>, <b>Arduino Leonardo</b> или <b>Arduino Micro</b>. У таких плат
    в Arduino IDE есть библиотека <code>Keyboard.h</code>, которая умеет
    притворяться клавиатурой «из коробки». Дороже способа выше и требует
    программирования платы, зато компактнее и опрятнее.</p>
<ul>
    <li>Один контакт ключа — на любой цифровой пин платы, например <b>D2</b>.</li>
    <li>Второй контакт ключа — на <b>GND</b> платы.</li>
</ul>
<p>Внешний резистор не нужен — прошивка ниже включает внутренний
    подтягивающий резистор пина (<code>INPUT_PULLUP</code>): пока ключ
    разомкнут, пин «видит» HIGH; в момент замыкания — LOW.</p>
<pre class="code-block"><code>#include &lt;Keyboard.h&gt;

const int KEY_PIN = 2;               // ключ: один контакт сюда, второй — на GND
const unsigned long DEBOUNCE_MS = 5; // антидребезг контактов

bool pressed = false;      // уже отправлен ли HID "пробел вниз"
bool lastReading = HIGH;   // последнее сырое чтение пина
unsigned long lastChangeAt = 0;

void setup() {
  pinMode(KEY_PIN, INPUT_PULLUP); // разомкнут = HIGH, замкнут = LOW
  Keyboard.begin();
}

void loop() {
  bool reading = digitalRead(KEY_PIN);

  if (reading != lastReading) {
    lastChangeAt = millis();
    lastReading = reading;
  }

  if (millis() - lastChangeAt > DEBOUNCE_MS) {
    bool keyDown = (reading == LOW);
    if (keyDown && !pressed) {
      Keyboard.press(' ');
      pressed = true;
    } else if (!keyDown && pressed) {
      Keyboard.release(' ');
      pressed = false;
    }
  }
}
</code></pre>
<p>Прошивается как обычный Arduino-скетч: Arduino IDE → «Инструменты →
    Плата» → «Arduino Leonardo» (для настоящего Leonardo/Micro) или
    «SparkFun Pro Micro» через менеджер плат для клона Pro Micro → выбрать
    порт в «Инструменты → Порт» → «Загрузить». Arduino Uno и Nano (на
    ATmega328P) для этого не подойдут — у них нет встроенной поддержки
    <code>Keyboard.h</code>.</p>

